"""Design2Code backend.

Serves the web UI and streams website code generated by Claude from
design screenshots + a functionality description.

Run:
    pip install -r requirements.txt
    export ANTHROPIC_API_KEY=sk-ant-...     # optional; the UI can also send a key
    python app.py                            # then open http://127.0.0.1:5000
"""
import os

import anthropic
from flask import Flask, Response, jsonify, request, send_from_directory

BASE_DIR = os.path.dirname(os.path.abspath(__file__))

app = Flask(__name__, static_folder=None)
app.config["MAX_CONTENT_LENGTH"] = 30 * 1024 * 1024  # screenshots are base64, allow room

ALLOWED_MODELS = {"claude-sonnet-5-5", "claude-opus-5-5", "claude-haiku-5-5"}
DEFAULT_MODEL = "claude-sonnet-5-5"
MAX_TOKENS = 16000

SYSTEM_PROMPT = """You are an expert front-end engineer. You are given screenshot(s) of a website design and a description of its functionality. Build the complete, working website.

Rules:
- Recreate the design as faithfully as possible: layout, spacing, colors, typography, sizes, borders, shadows, icons (use inline SVG or unicode), and content/text visible in the screenshot.
- Implement ALL the described functionality with real working JavaScript (no placeholders, no TODOs). Also add sensible interactions the design obviously implies (hover states, menu toggles, etc.).
- Make it fully responsive (desktop, tablet, mobile) using modern CSS (flexbox/grid, media queries).
- Use semantic, accessible HTML. Use only vanilla HTML/CSS/JS. You may load fonts from Google Fonts. Do not depend on build tools.
- For images that cannot be reproduced, use CSS gradients, inline SVG, or https://picsum.photos placeholders sized appropriately.
- If several screenshots are given, build them as sections or pages of ONE site (use hash-based navigation or show/hide sections so it works inside a single index.html).
- Output ONLY code, no explanations, using this exact format for every file:

=== FILE: index.html ===
<file contents>
=== FILE: style.css ===
<file contents>

Do not wrap the contents in markdown code fences."""


@app.get("/")
def index():
    return send_from_directory(BASE_DIR, "index.html")


@app.post("/api/generate")
def generate():
    data = request.get_json(silent=True) or {}
    messages = data.get("messages")
    model = data.get("model") or DEFAULT_MODEL

    if not isinstance(messages, list) or not messages:
        return jsonify(error="No messages provided."), 400
    if model not in ALLOWED_MODELS:
        return jsonify(error=f"Unsupported model: {model}"), 400

    api_key = request.headers.get("x-api-key", "").strip() or os.environ.get("ANTHROPIC_API_KEY", "")
    if not api_key:
        return jsonify(error="No API key. Enter one in the sidebar or set ANTHROPIC_API_KEY on the server."), 401

    client = anthropic.Anthropic(api_key=api_key)

    def stream():
        try:
            with client.messages.stream(
                model=model,
                max_tokens=MAX_TOKENS,
                system=SYSTEM_PROMPT,
                messages=messages,
            ) as s:
                for text in s.text_stream:
                    yield text
        except anthropic.AuthenticationError:
            yield "[[STREAM_ERROR]] Invalid API key."
        except anthropic.RateLimitError:
            yield "[[STREAM_ERROR]] Rate limit reached. Wait a moment and try again."
        except anthropic.APIStatusError as e:
            yield f"[[STREAM_ERROR]] API error {e.status_code}: {e.message}"
        except anthropic.APIConnectionError:
            yield "[[STREAM_ERROR]] Could not reach the Anthropic API."
        except Exception as e:  # keep the stream well-formed for the UI
            yield f"[[STREAM_ERROR]] {type(e).__name__}: {e}"

    return Response(
        stream(),
        mimetype="text/plain; charset=utf-8",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )


if __name__ == "__main__":
    port = int(os.environ.get("PORT", "5000"))
    app.run(host="127.0.0.1", port=port, debug=False, threaded=True)
